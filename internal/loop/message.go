// CommitMessage is the message for a landed fix.
//
// Prose explaining why, with the measurement that justifies it, because the
// claim "this is fixed" is only worth what the verification behind it is
// worth. No co-author or tool trailer is added: the commit is authored by
// whoever configured the repository, and this says Vibe Giver generated it in
// words, where a reader will see it.
func CommitMessage(f contract.Finding, out *Outcome, p *fix.Proposal) string {
	var b strings.Builder

	fmt.Fprintf(&b, "Fix %s (%s)\n\n", strings.TrimSuffix(f.Title, "."), f.FindingID)

	fmt.Fprintf(&b, "%s\n\n", wrap(f.Evidence.Summary, 72))

	if p.RootCause != "" {
		fmt.Fprintf(&b, "%s\n\n", wrap(p.RootCause, 72))
	}
	if p.Rationale != "" {
		fmt.Fprintf(&b, "%s\n\n", wrapParagraphs(p.Rationale, 72))
	}

	b.WriteString("Verified, not assumed:\n")
	for _, g := range out.VerificationResults {
		fmt.Fprintf(&b, "  %-20s %s\n", g.Gate, g.Outcome)
	}
	b.WriteString("\n")

	if len(out.Caveats) > 0 {
		b.WriteString("Not verified:\n")
		for _, c := range out.Caveats {
			fmt.Fprintf(&b, "  %s\n", wrapIndent(c, 70, "  "))
		}
		b.WriteString("\n")
	}

	if len(p.EnvVars) > 0 {
		b.WriteString("Configuration this change introduces:\n")
		for _, e := range p.EnvVars {
			fmt.Fprintf(&b, "  %s  %s\n", e.Name, e.Purpose)
			fmt.Fprintf(&b, "      default: %s\n", e.Default)
		}
		b.WriteString("\n")
	}

	if p.SiblingNote != "" {
		fmt.Fprintf(&b, "%s\n\n", wrap(p.SiblingNote, 72))
	}

	fmt.Fprintf(&b, "Generated by Vibe Giver from Vibe Killer finding %s, and verified by re-running\n", f.FindingID)
	fmt.Fprintf(&b, "Killer's own check (%s). Review before merging.\n", f.RuleID)

	return b.String()
}

// PullRequestTitle is the title in the brief sixth section.
func PullRequestTitle(f contract.Finding) string {
	return fmt.Sprintf("[Vibe Giver] Fix %s (%s)", strings.TrimSuffix(f.Title, "."), f.FindingID)
}

// PullRequestBody assembles the review packet.
//
// The order is the brief order and it is the order a reviewer needs: what the
// weakness was, the proof it was real before anything changed, the proof it is
// gone now, then the change itself. A security patch that arrives without the
// before-proof asks the reviewer to take the tool word for the existence of
// the problem as well as for the fix.
func PullRequestBody(f contract.Finding, out *Outcome, before contract.Verdict, patch string) string {
	var b strings.Builder

	b.WriteString("## What was wrong\n\n")
	fmt.Fprintf(&b, "%s\n\n", f.Evidence.Summary)

	b.WriteString("| | |\n|---|---|\n")
	fmt.Fprintf(&b, "| Finding | `%s` |\n", f.FindingID)
	fmt.Fprintf(&b, "| Rule | `%s` |\n", f.RuleID)
	fmt.Fprintf(&b, "| Severity | %s |\n", f.Severity)
	fmt.Fprintf(&b, "| Confidence | %s |\n", f.Confidence)
	if f.CWE != "" {
		fmt.Fprintf(&b, "| CWE | %s |\n", f.CWE)
	}
	fmt.Fprintf(&b, "| Category | %s |\n", f.Category)
	where := f.Location.File
	if f.Location.Line > 0 {
		where = fmt.Sprintf("%s:%d", f.Location.File, f.Location.Line)
	}
	if where != "" {
		fmt.Fprintf(&b, "| Where | `%s` |\n", where)
	}
	b.WriteString("\n")

	if f.Remediation.RootCauseHint != "" {
		fmt.Fprintf(&b, "**Killer's root-cause note:** %s\n\n", f.Remediation.RootCauseHint)
	}

	b.WriteString("## Proof it was real\n\n")
	b.WriteString("Before changing anything, the check that produced this finding was run again against ")
	b.WriteString("this tree, and it still reported the weakness:\n\n")
	fmt.Fprintf(&b, "```\n%s\n```\n\n", before.String())
	if out.BaseNote != "" {
		fmt.Fprintf(&b, "%s\n\n", out.BaseNote)
	}

	b.WriteString("## Proof it is fixed\n\n")
	b.WriteString("Every gate below had to return `gone`. An `inconclusive` result is a failure here, ")
	b.WriteString("never a pass, so a fix that could not be re-checked is not proposed at all.\n\n")
	b.WriteString("| Gate | Outcome | What it establishes |\n|---|---|---|\n")
	for _, g := range out.VerificationResults {
		fmt.Fprintf(&b, "| `%s` | **%s** | %s |\n", g.Gate, g.Outcome, oneLine(g.Reason))
	}
	b.WriteString("\n")

	if len(out.Caveats) > 0 {
		b.WriteString("### What was not verified\n\n")
		for _, c := range out.Caveats {
			fmt.Fprintf(&b, "- %s\n", c)
		}
		b.WriteString("\nThese are gates that could not run here. They are not failures and they are not ")
		b.WriteString("passes; they are things nobody checked, and they are listed so that reviewing this ")
		b.WriteString("change does not start from a false impression of how much was proven.\n\n")
	}

	b.WriteString("## The change\n\n")
	if out.RootCause != "" {
		fmt.Fprintf(&b, "%s\n\n", out.RootCause)
	}
	if out.Rationale != "" {
		fmt.Fprintf(&b, "%s\n\n", out.Rationale)
	}

	if len(out.EnvVars) > 0 {
		b.WriteString("### Before deploying this\n\n")
		for _, e := range out.EnvVars {
			req := ""
			if e.Required {
				req = " **(must be set, or the feature it guards stays off)**"
			}
			fmt.Fprintf(&b, "- `%s`%s — %s. Default: %s.\n", e.Name, req, e.Purpose, e.Default)
		}
		b.WriteString("\n")
	}

	if out.SiblingNote != "" {
		b.WriteString("### Follow-up\n\n")
		fmt.Fprintf(&b, "%s\n\n", out.SiblingNote)
	}

	if patch != "" {
		b.WriteString("<details>\n<summary>Diff</summary>\n\n```diff\n")
		b.WriteString(patch)
		if !strings.HasSuffix(patch, "\n") {
			b.WriteString("\n")
		}
		b.WriteString("```\n\n</details>\n\n")
	}

	b.WriteString("---\n\n")
	fmt.Fprintf(&b, "Generated by Vibe Giver from Vibe Killer `%s` finding `%s`. ",
		contract.PinnedKiller().PinnedTag, f.FindingID)
	b.WriteString("Vibe Giver does not merge: a person reviews every change it proposes.\n")

	return b.String()
}

// HumanActionReport is the brief seventh section: the findings Giver will not
// fix, with the reason and what to do instead.
func HumanActionReport(rep *Report) string {
	var needs []Outcome
	for _, o := range rep.Outcomes {
		switch o.Status {
		case StatusHumanRequired, StatusBlockedUnverifiable, StatusFixFailed, StatusSkipped:
			needs = append(needs, o)
		}
	}
	if len(needs) == 0 {
		return ""
	}

	var b strings.Builder
	b.WriteString("# Findings Vibe Giver did not fix\n\n")
	b.WriteString("Each of these is still open. None of them has been made safe, and the reason is ")
	b.WriteString("stated rather than implied.\n\n")

	for _, o := range needs {
		fmt.Fprintf(&b, "## %s — %s\n\n", o.FindingID, o.Title)
		fmt.Fprintf(&b, "- **Rule:** `%s`\n- **Severity:** %s\n- **Status:** `%s`\n\n",
			o.RuleID, o.Severity, o.Status)
		fmt.Fprintf(&b, "%s\n\n", o.Reason)
		fmt.Fprintf(&b, "%s\n\n", nextSteps(o))
	}
	return b.String()
}

func nextSteps(o Outcome) string {
	switch o.Status {
	case StatusHumanRequired:
		if o.Category == string(contract.CategorySecretsExposure) {
			return "**What to do.** A leaked credential is not fixed by editing code, and Vibe Giver " +
				"will not try: an edit that removes the string from the working tree leaves the " +
				"credential valid and still in the history, while making the finding disappear.\n\n" +
				"1. Rotate the credential in the provider console first. Until that is done, nothing " +
				"else matters — the old value is compromised.\n" +
				"2. Replace the literal in the code with a read from the environment or a secret store.\n" +
				"3. Purge it from history, for example with `git filter-repo --replace-text`, and force-push.\n" +
				"4. Confirm it is gone from anything already built and shipped — a client bundle, a " +
				"container image, a published artifact — since those carry their own copy.\n" +
				"5. Re-run Vibe Killer to confirm the finding is gone for the right reason."
		}
		return "**What to do.** Killer marked this as needing a person. Read its guidance in the " +
			"finding and act on it, then re-scan."
	case StatusBlockedUnverifiable:
		return "**What to do.** Nothing was changed, because a fix here could not have been proven. " +
			"Make the check runnable — most often by scanning a running instance with `--target` and " +
			"`--i-own-this-target`, or by installing the scanner the check needs — and run Vibe Giver " +
			"again. A fix applied without a working check is indistinguishable from no fix at all."
	case StatusFixFailed:
		return "**What to do.** A change was generated and did not pass the gates, so it was discarded " +
			"and the branch was removed. The rejected diff and the full gate output are in the run " +
			"directory, which is the place to start if the fix looks close."
	case StatusSkipped:
		return "**What to do.** This build has no strategy for this rule yet. Fix it by hand using " +
			"Killer's guidance for the finding."
	default:
		return ""
	}
}

// --- text helpers ----------------------------------------------------------

func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.Join(strings.Fields(s), " ")
}

func wrap(s string, width int) string { return wrapIndent(s, width, "") }

func wrapIndent(s string, width int, indent string) string {
	words := strings.Fields(s)
	if len(words) == 0 {
		return ""
	}
	var b strings.Builder
	line := indent + words[0]
	for _, w := range words[1:] {
		if len(line)+1+len(w) > width {
			b.WriteString(line + "\n")
			line = indent + w
			continue
		}
		line += " " + w
	}
	b.WriteString(line)
	return b.String()
}

func wrapParagraphs(s string, width int) string {
	paras := strings.Split(strings.ReplaceAll(s, "\r\n", "\n"), "\n\n")
	out := make([]string, 0, len(paras))
	for _, p := range paras {
		if strings.TrimSpace(p) == "" {
			continue
		}
		out = append(out, wrap(p, width))
	}
	return strings.Join(out, "\n\n")
}
